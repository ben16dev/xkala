    // MARK: - Lógica de sets (uniforme)

    private func ensureSetForMetricEdit() {
        guard entry.sets.isEmpty else { return }
        entry.sets.append(SetRecord.make(for: entry.exercise))
        normalizeSetsToExerciseRules()
    }

    private func resizeSets(to targetCount: Int) {
        let safeTarget = max(0, targetCount)
        let current = entry.sets.count
        guard safeTarget != current else { return }

        if safeTarget == 0 {
            for set in entry.sets {
                context.delete(set)
            }
            entry.sets.removeAll()
            return
        }

        if safeTarget > current {
            let extra = safeTarget - current
            for _ in 0..<extra {
                entry.sets.append(SetRecord.make(for: entry.exercise))
            }
        } else {
            let removeCount = current - safeTarget
            for _ in 0..<removeCount {
                if let last = entry.sets.last {
                    context.delete(last)
                    entry.sets.removeLast()
                }
            }
        }

        normalizeSetsToExerciseRules()
    }

    private func applyRepsToAll(_ reps: Int) {
        ensureSetForMetricEdit()
        for s in entry.sets {
            s.reps = reps
            s.seconds = nil
        }
        if !entry.exercise.loadAllowed {
            for s in entry.sets { s.loadKg = nil }
        }
    }

    private func applySecondsToAll(_ seconds: Int) {
        ensureSetForMetricEdit()
        for s in entry.sets {
            s.seconds = seconds
            if !entry.exercise.isIntermittentHangboardExercise {
                s.reps = nil
            }
        }
        if !entry.exercise.loadAllowed {
            for s in entry.sets { s.loadKg = nil }
        }
    }

    private func applyIntermittentWorkSecondsToAll(_ seconds: Int) {
        ensureSetForMetricEdit()
        for s in entry.sets {
            s.seconds = max(0, seconds)
        }
    }

    private func applyIntermittentRoundsToAll(_ rounds: Int) {
        ensureSetForMetricEdit()
        for s in entry.sets {
            s.reps = max(0, rounds)
        }
    }

    private func applyLoadToAll(_ load: Double) {
        ensureSetForMetricEdit()
        guard entry.exercise.loadAllowed else {
            for s in entry.sets { s.loadKg = nil }
            return
        }
        for s in entry.sets {
            s.loadKg = load
        }
    }

    private func normalizeSetsToExerciseRules() {
        guard !entry.sets.isEmpty else { return }

        if entry.exercise.isIntermittentHangboardExercise {
            for s in entry.sets {
                if s.seconds == nil { s.seconds = 0 }
                if s.reps == nil { s.reps = 0 }
                if entry.exercise.loadAllowed, s.loadKg == nil { s.loadKg = 0 }
            }
            if !entry.exercise.loadAllowed {
                for s in entry.sets { s.loadKg = nil }
            }
            return
        }

        if entry.exercise.modeEnum == .reps {
            for s in entry.sets { s.seconds = nil }
        } else {
            for s in entry.sets { s.reps = nil }
        }

        if !entry.exercise.loadAllowed {
            for s in entry.sets { s.loadKg = nil }
        }
    }

    private func intermittentRestSeconds(from notes: String) -> Int? {
        let pattern = #"\[intermittent_rest_seconds=(\d+)\]"#
        guard
            let regex = try? NSRegularExpression(pattern: pattern),
            let match = regex.firstMatch(in: notes, range: NSRange(notes.startIndex..., in: notes)),
            match.numberOfRanges > 1,
            let valueRange = Range(match.range(at: 1), in: notes)
        else {
            return nil
        }
        return Int(notes[valueRange])
    }

    private func writingIntermittentRestSeconds(_ seconds: Int, into notes: String) -> String {
        let safeValue = max(0, seconds)
        let token = "[intermittent_rest_seconds=\(safeValue)]"
        let pattern = #"\[intermittent_rest_seconds=\d+\]"#

        if let range = notes.range(of: pattern, options: .regularExpression) {
            var updated = notes
            updated.replaceSubrange(range, with: token)
            return updated
        }

        let trimmed = notes.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty {
            return token
        }
        return "\(notes)\n\(token)"
    }

    // MARK: - Keyboard

    private func hideKeyboard() {
        UIApplication.shared.sendAction(
            #selector(UIResponder.resignFirstResponder),
            to: nil,
            from: nil,
            for: nil
        )
    }
}

// MARK: - Controles

private struct IntControlRow: View {
    let title: String
    @Binding var value: Int
    let range: ClosedRange<Int>
    let step: Int

    @State private var text: String = ""
    @FocusState private var focused: Bool

    var body: some View {
        HStack(spacing: 12) {
            Text(title)
            Spacer()

            EditableControlPill(
                text: Binding(
                    get: { text.isEmpty ? "\(value)" : text },
                    set: { text = $0 }
                ),
                suffix: nil,
                keyboard: .numberPad,
                canDecrement: value - step >= range.lowerBound,
                canIncrement: value + step <= range.upperBound,
                decrement: { value = max(value - step, range.lowerBound) },
                increment: { value = min(value + step, range.upperBound) },
                onCommit: {
                    let digits = text.filter { $0.isNumber || $0 == "-" }
                    let parsed = Int(digits) ?? value
                    value = min(max(parsed, range.lowerBound), range.upperBound)
                    text = ""
                },
                focused: $focused
            )
        }
    }
}

private struct DoubleControlRow: View {
    let title: String
    let suffix: String
    @Binding var value: Double
    let range: ClosedRange<Double>
    let step: Double
    let decimals: Int

    @State private var text: String = ""
    @FocusState private var focused: Bool

    var body: some View {
        HStack(spacing: 12) {
            Text(title)
            Spacer()

            let formatted = String(format: "%.\(decimals)f", value)

            EditableControlPill(
                text: Binding(
                    get: { text.isEmpty ? formatted : text },
                    set: { text = $0 }
                ),
                suffix: suffix,
                keyboard: .decimalPad,
                canDecrement: value - step >= range.lowerBound - 0.0001,
                canIncrement: value + step <= range.upperBound + 0.0001,
                decrement: { value = max(value - step, range.lowerBound) },
                increment: { value = min(value + step, range.upperBound) },
                onCommit: {
                    let cleaned = text
                        .replacingOccurrences(of: ",", with: ".")
                        .filter { $0.isNumber || $0 == "." || $0 == "-" }

                    let parsed = Double(cleaned) ?? value
                    value = min(max(parsed, range.lowerBound), range.upperBound)
                    text = ""
                },
                focused: $focused
            )
        }
    }
}

private struct TimeControlRow: View {
    let title: String
    @Binding var seconds: Int
    let range: ClosedRange<Int>
    let stepSeconds: Int

    @State private var text: String = ""
    @FocusState private var focused: Bool

    var body: some View {
        HStack(spacing: 12) {
            Text(title)
            Spacer()

            let display = formatMMSS(seconds)

            EditableControlPill(
                text: Binding(
                    get: { text.isEmpty ? display : text },
                    set: { text = $0 }
                ),
                suffix: "min",
                keyboard: .numbersAndPunctuation,
                canDecrement: seconds - stepSeconds >= range.lowerBound,
                canIncrement: seconds + stepSeconds <= range.upperBound,
                decrement: { seconds = max(seconds - stepSeconds, range.lowerBound) },
                increment: { seconds = min(seconds + stepSeconds, range.upperBound) },
                onCommit: {
                    let parsed = parseMMSS(text) ?? seconds
                    seconds = min(max(parsed, range.lowerBound), range.upperBound)
                    text = ""
                },
                focused: $focused
            )
        }
    }

    private func formatMMSS(_ totalSeconds: Int) -> String {
        let s = max(0, totalSeconds)
        let m = s / 60
        let r = s % 60
        return "\(m):" + String(format: "%02d", r)
    }

    private func parseMMSS(_ input: String) -> Int? {
        let trimmed = input.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty { return nil }

        if trimmed.contains(":") {
            let parts = trimmed.split(separator: ":", omittingEmptySubsequences: false)
            guard parts.count == 2 else { return nil }
            let mStr = parts[0].filter(\.isNumber)
            let sStr = parts[1].filter(\.isNumber)
            let m = Int(mStr) ?? 0
            let s = Int(sStr) ?? 0
            return max(0, m * 60 + min(s, 59))
        }

        let digits = trimmed.filter { $0.isNumber }
        return Int(digits)
    }
}

private struct EditableControlPill: View {
    @Binding var text: String
    let suffix: String?
    let keyboard: UIKeyboardType

    let canDecrement: Bool
    let canIncrement: Bool
    let decrement: () -> Void
    let increment: () -> Void

    let onCommit: () -> Void
    @FocusState.Binding var focused: Bool

    var body: some View {
        HStack(spacing: 10) {
            Button(action: decrement) {
                Image(systemName: "minus")
                    .font(.system(size: 14, weight: .semibold))
                    .frame(width: 28, height: 28)
            }
            .buttonStyle(.borderless)
            .disabled(!canDecrement)

            HStack(spacing: 6) {
                TextField("", text: $text)
                    .keyboardType(keyboard)
                    .focused($focused)
                    .multilineTextAlignment(.center)
                    .font(.system(.body, design: .rounded))
                    .monospacedDigit()
                    .frame(minWidth: 70)
                    .onSubmit { commitAndDismiss() }
                    .onChange(of: focused) { _, isFocused in
                        if !isFocused { onCommit() }
                    }

                if let suffix {
                    Text(suffix)
                        .foregroundStyle(.secondary)
                        .font(.system(.footnote, design: .rounded))
                }
            }
            .contentShape(Rectangle())
            .onTapGesture { focused = true }

            Button(action: increment) {
                Image(systemName: "plus")
                    .font(.system(size: 14, weight: .semibold))
                    .frame(width: 28, height: 28)
            }
            .buttonStyle(.borderless)
            .disabled(!canIncrement)
        }
        .padding(.horizontal, 10)
        .padding(.vertical, 6)
        .background(.thinMaterial)
        .clipShape(Capsule())
    }

