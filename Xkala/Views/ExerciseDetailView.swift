import SwiftUI
import SwiftData
import UIKit

struct ExerciseDetailView: View {
    @Environment(\.modelContext) private var context
    @EnvironmentObject private var badgeUnlockCoordinator: BadgeUnlockCoordinator
    @Bindable var entry: WorkoutEntry
    var parentWorkoutHint: WorkoutDay? = nil

    @Query(sort: \WorkoutDay.date, order: .reverse) private var workouts: [WorkoutDay]

    @State private var completionPulse = false

    var body: some View {
        let isTest = entry.exercise.isTestExercise
        let progressSnapshot = ExerciseProgressCalculator.snapshot(for: entry, in: workouts)
        let basicStats = ExerciseProgressCalculator.basicStats(for: entry, in: workouts)
        let testSnapshot = isTest ? TestResultCalculator.snapshot(for: entry, in: workouts) : nil

        List {
            if !entry.exercise.notes.isEmpty {
                Section("Cómo se hace") {
                    Text(entry.exercise.notes)
                        .foregroundStyle(.secondary)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .xkalaCard()
                        .listRowSeparator(.hidden)
                        .listRowBackground(Color.clear)
                        .listRowInsets(EdgeInsets(top: 8, leading: 16, bottom: 8, trailing: 16))
                }
            }

            Section("Estado") {
                VStack(spacing: 12) {
                    Toggle(
                        "Ejercicio completado",
                        isOn: Binding(
                            get: { entry.isDone },
                            set: { newValue in
                                withAnimation(.spring(response: 0.28, dampingFraction: 0.75)) {
                                    entry.isDone = newValue
                                    if newValue { triggerCompletionFeedback() }
                                    parentWorkout?.syncAutoGeneratedSessionNameIfNeeded()
                                    try? context.save()
                                }
                            }
                        )
                    )

                    if entry.isDone {
                        HStack(spacing: 10) {
                            Image(systemName: "checkmark.circle.fill")
                                .font(.system(size: 20))
                                .foregroundStyle(XkalaTheme.mint)
                            Text("Completado")
                                .font(.subheadline)
                                .foregroundStyle(.secondary)
                            Spacer()
                        }
                        .scaleEffect(completionPulse ? 1.03 : 1.0)
                        .opacity(completionPulse ? 1.0 : 0.92)
                        .onAppear {
                            completionPulse = true
                            DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
                                withAnimation(.easeOut(duration: 0.25)) {
                                    completionPulse = false
                                }
                            }
                        }
                    }

                    if entry.usesBlockEditor || entry.usesTraverseEditor {
                        Toggle(
                            "Completado con éxito",
                            isOn: Binding(
                                get: { entry.climbSuccess ?? false },
                                set: { newValue in
                                    entry.climbSuccess = newValue
                                    try? context.save()
                                    evaluateBadgesAfterEntryChange(reason: .climbSuccess)
                                }
                            )
                        )
                    }

                    if !entry.usesBlockEditor && !entry.usesTraverseEditor {
                        IntControlRow(
                            title: "Intensidad",
                            value: $entry.intensity,
                            range: 1...3,
                            step: 1
                        )
                    }
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .xkalaCard()
                .listRowSeparator(.hidden)
                .listRowBackground(Color.clear)
                .listRowInsets(EdgeInsets(top: 8, leading: 16, bottom: 8, trailing: 16))
            }

            if isTest {
                Section {
                    HStack(spacing: 10) {
                        Image(systemName: "flag.checkered")
                            .font(.system(size: 16, weight: .semibold))
                            .foregroundStyle(XkalaTheme.mint)
                        Text("Esto es un test. Registra tus intentos válidos; Xkala tomará el mejor resultado.")
                            .font(.subheadline)
                            .foregroundStyle(.secondary)
                            .frame(maxWidth: .infinity, alignment: .leading)
                    }
                    .xkalaCard()
                    .listRowSeparator(.hidden)
                    .listRowBackground(Color.clear)
                    .listRowInsets(EdgeInsets(top: 8, leading: 16, bottom: 8, trailing: 16))
                }
            }

            Section("Registro") {
                VStack(spacing: 12) {
                    if entry.usesBlockEditor {
                        BlockEntryEditorView(entry: entry)
                    } else if entry.usesTraverseEditor {
                        TraverseEntryEditorView(entry: entry)
                    } else if entry.usesIntermittentHangboardEditor {
                        IntermittentHangboardEditorView(
                            workSeconds: Binding(
                                get: { entry.sets.first?.seconds ?? 0 },
                                set: { newValue in applyIntermittentWorkSecondsToAll(newValue) }
                            ),
                            restSeconds: Binding(
                                get: { intermittentRestSeconds(from: entry.entryNotes) ?? 0 },
                                set: { newValue in
                                    entry.entryNotes = writingIntermittentRestSeconds(newValue, into: entry.entryNotes)
                                }
                            ),
                            rounds: Binding(
                                get: { entry.sets.first?.reps ?? 0 },
                                set: { newValue in applyIntermittentRoundsToAll(newValue) }
                            ),
                            cycles: Binding(
                                get: { entry.sets.count },
                                set: { newCount in resizeSets(to: newCount) }
                            ),
                            loadKg: Binding(
                                get: { entry.sets.first?.loadKg ?? 0 },
                                set: { newValue in applyLoadToAll(newValue) }
                            ),
                            loadAllowed: entry.exercise.loadAllowed
                        )
                    } else {
                        if entry.usesCircuitEditor {
                            IntControlRow(
                                title: "Nº vueltas",
                                value: Binding(
                                    get: { entry.sets.first?.reps ?? 0 },
                                    set: { newValue in
                                        ensureSingleSetForCircuit()
                                        entry.sets.first?.reps = newValue
                                        entry.sets.first?.seconds = nil
                                        entry.sets.first?.loadKg = nil
                                    }
                                ),
                                range: 0...20,
                                step: 1
                            )
                        } else {
                            IntControlRow(
                                title: "Series",
                                value: Binding(
                                    get: { entry.sets.count },
                                    set: { newCount in
                                        resizeSets(to: newCount)
                                    }
                                ),
                                range: 0...30,
                                step: 1
                            )

                            if entry.exercise.modeEnum == .reps {
                                IntControlRow(
                                    title: repsTitle,
                                    value: Binding(
                                        get: { entry.sets.first?.reps ?? 0 },
                                        set: { newValue in
                                            applyRepsToAll(newValue)
                                        }
                                    ),
                                    range: 0...200,
                                    step: 1
                                )
                            } else {
                                TimeControlRow(
                                    title: "Tiempo",
                                    seconds: Binding(
                                        get: { entry.sets.first?.seconds ?? 0 },
                                        set: { newValue in
                                            applySecondsToAll(newValue)
                                        }
                                    ),
                                    range: 0...3600,
                                    stepSeconds: 5
                                )
                            }

                            if entry.exercise.loadAllowed {
                                DoubleControlRow(
                                    title: "Carga",
                                    suffix: "kg",
                                    value: Binding(
                                        get: { entry.sets.first?.loadKg ?? 0 },
                                        set: { newValue in
                                            applyLoadToAll(newValue)
                                        }
                                    ),
                                    range: -50...150,
                                    step: 0.5,
                                    decimals: 1
                                )
                            }
                        }
                    }
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .xkalaCard()
                .listRowSeparator(.hidden)
                .listRowBackground(Color.clear)
                .listRowInsets(EdgeInsets(top: 8, leading: 16, bottom: 8, trailing: 16))
            }

            Section("Estadísticas") {
                ExerciseBasicStatsSectionView(snapshot: basicStats)
            }

            if let testSnapshot {
                Section("Resultados del Test") {
                    ExerciseTestSectionView(exercise: entry.exercise, snapshot: testSnapshot)
                }
            } else {
                Section("Progreso") {
                    ExerciseProgressSectionView(snapshot: progressSnapshot)
                }
            }

        }
        .scrollContentBackground(.hidden)
        .listStyle(.plain)
        .xkalaScreenBackground(.calendar)
        .navigationTitle(entry.exercise.name)
        .toolbar {
            ToolbarItemGroup(placement: .keyboard) {
                Spacer()
                Button("OK") { hideKeyboard() }
            }
        }
        .onAppear {
            if !entry.sets.isEmpty {
                normalizeSetsToExerciseRules()
            }
        }
        .onChange(of: entry.isDone) { _, newValue in
            if newValue { triggerCompletionFeedback() }
            if newValue && (entry.usesBlockEditor || entry.usesTraverseEditor) {
                evaluateBadgesAfterEntryChange(reason: .climbSuccess)
            }
        }
        .onDisappear {
            evaluateBadgesAfterEntryChange(reason: .sessionChange)
        }
    }

    private var parentWorkout: WorkoutDay? {
        if let parentWorkoutHint { return parentWorkoutHint }
        return workouts.first { day in
            day.entries.contains { $0.persistentModelID == entry.persistentModelID }
        }
    }

    private func evaluateBadgesAfterEntryChange(reason: BadgeEvaluationTrigger.Reason) {
        BadgeEvaluationTrigger.evaluateBadgesAfterSessionChange(
            context: context,
            coordinator: badgeUnlockCoordinator,
            currentWorkout: parentWorkout,
            reason: reason
        )
    }

    // MARK: - Animación + Haptic

    private func triggerCompletionFeedback() {
        completionPulse = true
        let generator = UINotificationFeedbackGenerator()
        generator.notificationOccurred(.success)

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
            withAnimation(.easeOut(duration: 0.25)) {
                completionPulse = false
            }
        }
    }

    private func ensureSingleSetForCircuit() {
        if entry.sets.isEmpty {
            entry.sets.append(SetRecord.make(for: entry.exercise))
        }

        while entry.sets.count > 1 {
            if let last = entry.sets.last {
                context.delete(last)
                entry.sets.removeLast()
            } else {
                break
            }
        }

        entry.sets.first?.seconds = nil
        entry.sets.first?.loadKg = nil

        if entry.sets.first?.reps == nil {
            entry.sets.first?.reps = 0
        }
    }

    private func ensureSingleSetForClimb() {
        if entry.sets.isEmpty {
            entry.sets.append(SetRecord.make(for: entry.exercise))
        }

        while entry.sets.count > 1 {
            if let last = entry.sets.last {
                context.delete(last)
                entry.sets.removeLast()
            } else {
                break
            }
        }

        entry.sets.first?.seconds = nil
        entry.sets.first?.loadKg = nil
    }

    // MARK: - Texto

    private var repsTitle: String {
        let name = entry.exercise.name.lowercased()
        let cat = entry.exercise.exerciseCategoryKeyForSemantics
        if cat == "campus" || name.contains("campus") {
            return "Repeticiones"
        }
        return "Reps"
    }

    // MARK: - Bloques / Travesías editors

    private struct BlockEntryEditorView: View {
        @Bindable var entry: WorkoutEntry

        private var attemptsBinding: Binding<Int> {
            Binding(
                get: { entry.sets.first?.reps ?? 0 },
                set: { newValue in
                    if entry.sets.isEmpty { entry.sets.append(SetRecord.make(for: entry.exercise)) }
                    entry.sets.first?.reps = newValue
                    entry.sets.first?.seconds = nil
                    entry.sets.first?.loadKg = nil
                }
            )
        }

        private var identifierBinding: Binding<String> {
            Binding(
                get: { entry.climbIdentifier ?? "" },
                set: { newValue in
                    let trimmed = newValue.trimmingCharacters(in: .whitespacesAndNewlines)
                    entry.climbIdentifier = trimmed.isEmpty ? nil : trimmed
                }
            )
        }

        private let gradeOptions: [(String, Color)] = [
            ("green", .green),
            ("yellow", .yellow),
            ("orange", .orange),
            ("purple", .purple)
        ]

        var body: some View {
            VStack(spacing: 12) {
                TextField("Identificador", text: identifierBinding)
                    .textInputAutocapitalization(.words)
                    .autocorrectionDisabled(true)
                    .frame(maxWidth: .infinity, alignment: .leading)

                HStack(spacing: 14) {
                    ForEach(gradeOptions.indices, id: \.self) { idx in
                        let option = gradeOptions[idx]
                        let isSelected = entry.climbGradeColor == option.0
                        Button {
                            entry.climbGradeColor = option.0
                        } label: {
                            Circle()
                                .fill(option.1)
                                .frame(width: 22, height: 22)
                                .overlay {
                                    if isSelected {
                                        Circle().stroke(Color.primary, lineWidth: 2)
                                    }
                                }
                        }
                        .buttonStyle(.plain)
                    }
                }

                IntControlRow(
                    title: "Intentos",
                    value: attemptsBinding,
                    range: 0...200,
                    step: 1
                )
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    private struct TraverseEntryEditorView: View {
        @Bindable var entry: WorkoutEntry

        private var attemptsBinding: Binding<Int> {
            Binding(
                get: { entry.sets.first?.reps ?? 0 },
                set: { newValue in
                    if entry.sets.isEmpty { entry.sets.append(SetRecord.make(for: entry.exercise)) }
                    entry.sets.first?.reps = newValue
                    entry.sets.first?.seconds = nil
                    entry.sets.first?.loadKg = nil
                }
            )
        }

        private var identifierBinding: Binding<String> {
            Binding(
                get: { entry.climbIdentifier ?? "" },
                set: { newValue in
                    let upper = newValue.uppercased()
                    let firstLetter = upper.unicodeScalars.first(where: { scalar in
                        let v = scalar.value
                        return v >= 65 && v <= 90 // A-Z
                    })

                    if let firstLetter {
                        entry.climbIdentifier = String(UnicodeScalar(firstLetter.value)!)
                    } else {
                        entry.climbIdentifier = nil
                    }
                }
            )
        }

        var body: some View {
            VStack(spacing: 12) {
                TextField("Letra", text: identifierBinding)
                    .keyboardType(.alphabet)
                    .autocorrectionDisabled(true)
                    .textInputAutocapitalization(.characters)
                    .frame(maxWidth: .infinity, alignment: .leading)

                IntControlRow(
                    title: "Intentos",
                    value: attemptsBinding,
                    range: 0...200,
                    step: 1
                )
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    private struct IntermittentHangboardEditorView: View {
        @Binding var workSeconds: Int
        @Binding var restSeconds: Int
        @Binding var rounds: Int
        @Binding var cycles: Int
        @Binding var loadKg: Double
        let loadAllowed: Bool

        var body: some View {
            VStack(spacing: 12) {
                TimeControlRow(
                    title: "Tiempo ejercicio",
                    seconds: $workSeconds,
                    range: 0...600,
                    stepSeconds: 1
                )

                TimeControlRow(
                    title: "Tiempo descanso",
                    seconds: $restSeconds,
                    range: 0...600,
                    stepSeconds: 1
                )

                IntControlRow(
                    title: "Nº rondas",
                    value: $rounds,
                    range: 0...50,
                    step: 1
                )

                IntControlRow(
                    title: "Nº ciclos",
                    value: $cycles,
                    range: 0...30,
                    step: 1
                )

                if loadAllowed {
                    DoubleControlRow(
                        title: "Carga",
